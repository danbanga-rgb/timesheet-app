// ─── Invoice number generation ────────────────────────────────────────────────

async function generateInvoiceNumber(
  email: string,
  periodStart: string,
  supabase: ReturnType<typeof createClient>
): Promise<string> {
  const prefix = email.split('@')[0].replace(/[^a-zA-Z0-9]/g, '').toUpperCase().slice(0, 6);
  const yyyymm = periodStart.replace(/-/g, '').slice(0, 6);
  const pattern = `IMP-${prefix}-${yyyymm}-%`;

  const { count } = await supabase
    .from('invoices')
    .select('id', { count: 'exact', head: true })
    .eq('source', 'imported')
    .ilike('invoice_number', pattern);

  const seq = String((count ?? 0) + 1).padStart(2, '0');
  return `IMP-${prefix}-${yyyymm}-${seq}`;
}

// ─── Reconciliation ───────────────────────────────────────────────────────────

// Sum timesheet hours in a period. Extracted from reconcile so the anomaly
// detector can consume the same number pre-insert without duplicating logic.
// Returns { hours, lastCoveredDate, hadTimesheets } so callers can distinguish
// "no timesheets at all" from "0h summed".
async function sumTimesheetHours(
  userId: string,
  periodStart: string,
  periodEnd: string,
  supabase: ReturnType<typeof createClient>
): Promise<{ hours: number; lastCoveredDate: string; hadTimesheets: boolean } | null> {
  const rangeStart = new Date(periodStart + 'T12:00:00');
  rangeStart.setDate(rangeStart.getDate() - 6);
  const rangeStartStr = rangeStart.toISOString().slice(0, 10);

  const { data: timesheets, error } = await supabase
    .from('timesheets')
    .select('week_start, entries')
    .eq('user_id', userId)
    .gte('week_start', rangeStartStr)
    .lte('week_start', periodEnd);

  if (error) return null;
  if (!timesheets || timesheets.length === 0) {
    return { hours: 0, lastCoveredDate: periodStart, hadTimesheets: false };
  }

  let hours = 0;
  let lastCoveredDate = periodStart;
  for (const ts of timesheets) {
    const entries = (ts.entries || {}) as Record<string, unknown>;
    const wsStr = String((ts as { week_start: string }).week_start).slice(0, 10);
    const wsDate = new Date(wsStr + 'T12:00:00');
    const weekSun = new Date(wsDate);
    weekSun.setDate(wsDate.getDate() + 6);
    const weekSunStr = weekSun.toISOString().slice(0, 10);
    const coveredThroughStr = weekSunStr > periodEnd ? periodEnd : weekSunStr;
    if (coveredThroughStr > lastCoveredDate) lastCoveredDate = coveredThroughStr;

    for (const [date, entry] of Object.entries(entries)) {
      if (date < periodStart || date > periodEnd) continue;
      let h = 0;
      if (typeof entry === 'number') h = entry;
      else if (entry && typeof entry === 'object') {
        const raw = (entry as { hours?: string | number }).hours;
        h = typeof raw === 'number' ? raw : parseFloat(String(raw ?? 0));
      }
      if (!isNaN(h) && h > 0) hours += h;
    }
  }
  return { hours, lastCoveredDate, hadTimesheets: true };
}

// Identity context for the anomaly detector: the list of company names on the
// resolved user's payment_profiles, the currencies of their recent invoices, and
// the profile name. Fed to detector so it can flag on-behalf-of forwarders and
// bilingual-currency parse errors. Non-fatal on error (empty context = rules skip).
async function getIdentityContext(
  userId: string,
  supabase: ReturnType<typeof createClient>,
): Promise<{ companies: string[]; currencies: string[]; contractorName: string | null }> {
  try {
    const [profilesRes, invoicesRes, meRes] = await Promise.all([
      supabase.from('payment_profiles').select('company_name').eq('user_id', userId),
      supabase.from('invoices')
        .select('currency')
        .eq('user_id', userId)
        .in('status', ['approved', 'paid'])
        .not('currency', 'is', null)
        .order('period_start', { ascending: false })
        .limit(5),
      supabase.from('profiles').select('name').eq('id', userId).maybeSingle(),
    ]);
    const companies = ((profilesRes.data ?? []) as Array<{ company_name: string | null }>)
      .map(r => (r.company_name ?? '').trim())
      .filter(s => s.length >= 3);
    const currencies = ((invoicesRes.data ?? []) as Array<{ currency: string | null }>)
      .map(r => (r.currency ?? '').trim())
      .filter(s => s.length > 0);
    const contractorName = ((meRes.data as { name?: string | null } | null)?.name ?? null);
    return { companies, currencies, contractorName };
  } catch {
    return { companies: [], currencies: [], contractorName: null };
  }
}

// Phantom-profile guard: does the parsed IBAN already belong to a DIFFERENT user's
// payment_profile? If yes, the sender is almost certainly forwarding on-behalf-of
// (or a Convera intermediary hit). Used to block auto-INSERT of a duplicate profile
// under the sender's user_id (Aug 2026 Naretena pp id=100 phantom incident).
// Returns list of {user_id, profile_id} pairs owning the IBAN under other users.
async function findIbanOwnedByOtherUser(
  iban: string,
  userId: string,
  supabase: ReturnType<typeof createClient>,
): Promise<Array<{ userId: string; profileId: number }>> {
  if (!iban || iban.length < 8) return [];
  const { data } = await supabase
    .from('payment_profiles')
    .select('id, user_id, iban')
    .ilike('iban', iban);
  return ((data ?? []) as Array<{ id: number; user_id: string; iban: string | null }>)
    .filter(r => r.user_id !== userId)
    .map(r => ({ userId: r.user_id, profileId: r.id }));
}

// Most common rate from contractor's approved invoices in 6 months before
// `beforeDate`. Used by the anomaly detector to fill missing rates or verify
// implausible ones. Returns null if no prior approved invoices with a rate.
async function getPriorRate(
  userId: string,
  beforeDate: string,
  supabase: ReturnType<typeof createClient>
): Promise<number | null> {
  const cutoff = new Date(beforeDate + 'T12:00:00Z');
  cutoff.setMonth(cutoff.getMonth() - 6);
  const cutoffStr = cutoff.toISOString().slice(0, 10);
  const { data } = await supabase
    .from('invoices')
    .select('rate')
    .eq('user_id', userId)
    .gte('period_start', cutoffStr)
    .lt('period_start', beforeDate)
    .in('status', ['approved', 'paid'])
    .not('rate', 'is', null);
  if (!data || data.length === 0) return null;
  const counts = new Map<number, number>();
  for (const r of data) {
    const rate = Number((r as { rate: number | string }).rate);
    if (rate > 0) counts.set(rate, (counts.get(rate) || 0) + 1);
  }
  if (counts.size === 0) return null;
  let bestRate: number | null = null;
  let bestCount = 0;
  for (const [rate, count] of counts) if (count > bestCount) { bestRate = rate; bestCount = count; }
  return bestRate;
}

async function reconcile(
  userId: string,
  periodStart: string,
  periodEnd: string,
  invoiceHours: number,
  supabase: ReturnType<typeof createClient>
): Promise<{
  status: 'matched' | 'mismatch' | 'unverifiable' | 'pending_final_week' | 'undercharged';
  delta: number | null;
  notes: string;
}> {
  const summed = await sumTimesheetHours(userId, periodStart, periodEnd, supabase);
  if (summed === null) {
    return { status: 'unverifiable', delta: null, notes: 'DB error during reconciliation' };
  }
  if (!summed.hadTimesheets) {
    return { status: 'unverifiable', delta: null, notes: 'No timesheets found for period' };
  }
  const timesheetHours = summed.hours;
  const lastCoveredDate = summed.lastCoveredDate;

  if (timesheetHours === 0) {
    return { status: 'unverifiable', delta: null, notes: `Timesheet: 0h · Invoice: ${invoiceHours}h · Zero hours in period` };
  }

  const delta = Math.round((invoiceHours - timesheetHours) * 100) / 100;

  // Δ = 0 → matched
  if (Math.abs(delta) < 0.01) {
    return { status: 'matched', delta: 0, notes: `Timesheet: ${timesheetHours}h · Invoice: ${invoiceHours}h` };
  }

  // Δ < 0 → contractor billed us less than the timesheet shows. No financial risk (we may
  // still bill the client using our estimated/timesheet hours). Tag as `undercharged`; SLO skips it.
  if (delta < 0) {
    return {
      status: 'undercharged',
      delta,
      notes: `Timesheet: ${timesheetHours}h · Invoice: ${invoiceHours}h · Contractor billed ${Math.abs(delta)}h less than timesheet (no action)`,
    };
  }

  // Δ > 0 → contractor billed us MORE than the timesheet shows. If invoice period extends past
  // the last submitted week and Δ can be explained by pending weekdays (≤ 10h/day), tag it as
  // pending_final_week — resolves automatically when the trailing week's timesheet arrives.
  if (lastCoveredDate < periodEnd) {
    // Count weekdays after lastCoveredDate through periodEnd
    let missingWeekdays = 0;
    const cursor = new Date(lastCoveredDate + 'T12:00:00');
    const endD = new Date(periodEnd + 'T12:00:00');
    cursor.setDate(cursor.getDate() + 1);
    while (cursor <= endD) {
      const dow = cursor.getDay();
      if (dow !== 0 && dow !== 6) missingWeekdays++;
      cursor.setDate(cursor.getDate() + 1);
    }
    // Allow up to 10h/day slack for overtime patterns
    if (delta <= missingWeekdays * 10 + 0.01) {
      return {
        status: 'pending_final_week',
        delta,
        notes: `Timesheet: ${timesheetHours}h · Invoice: ${invoiceHours}h · +${delta}h consistent with ${missingWeekdays} pending weekday(s) after ${lastCoveredDate}`,
      };
    }
  }

  // Δ > 0 and not explained by pending week → real mismatch. This is the "we may pay more than
  // we invoiced the client" case (Nikolina/Marta risk). SLO fires.
  return {
    status: 'mismatch',
    delta,
    notes: `Timesheet: ${timesheetHours}h · Invoice: ${invoiceHours}h`,
  };
}

// ─── Main handler ─────────────────────────────────────────────────────────────

serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: corsHeaders });

  // ── Auth ──────────────────────────────────────────────────────────────────
  const ingestSecret = Deno.env.get('INGEST_SECRET');
  const provided     = req.headers.get('x-ingest-secret');
  if (!ingestSecret || provided !== ingestSecret) {
    return new Response(JSON.stringify({ error: 'Unauthorized' }), {
      status: 401, headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    });
  }

  const supabase = createClient(
    Deno.env.get('SUPABASE_URL')!,
    Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!,
  );

  let body: Record<string, unknown>;
  try { body = await req.json(); }
  catch {
    return new Response(JSON.stringify({ error: 'Invalid JSON' }), {
      status: 400, headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    });
  }

  const {
    messageId,
    contractorEmail,
    contractorName,
    subject,
    attachmentName,
    forwardedBy,
    // Parser output contract fields
    invoiceNumber,
    periodStart,
    periodEnd,
    totalHours,
    rate,
    totalAmount,
    currency,
    paymentDetails,
    parseNotes,
    // Raw PDF for storage upload (base64-encoded, optional)
    pdfBase64,
    // Multi-contractor grouping key (set for grouped invoices; null for single)
    groupKey,
    // True when subject/body contains correction keywords ("fixed", "revised", etc.)
    correctionHint,
    // SHA-256 hex digest of the attachment bytes (for dedup analytics)
    attachmentHash,
    // Phase 1 shadow verification: Groq vision's parse of the same PDF for later comparison.
    // Never affects the invoice row — logged only. See project-parser-verification.
    groqVisionVerification,
  } = body as Record<string, unknown>;

  if (!messageId || !contractorEmail) {
    return new Response(JSON.stringify({ error: 'Missing: messageId, contractorEmail' }), {
      status: 400, headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    });
  }

  // Only accept invoices forwarded by an internal accountant.
  // Direct contractor submissions are rejected — accounting reviews before the system ingests.
  if (!forwardedBy) {
    await supabase.from('email_invoice_log').insert({
      message_id:      messageId,
      from_email:      contractorEmail,
      subject:         subject || null,
      attachment_name: attachmentName || null,
      parse_status:    'failed',
      parse_notes:     'Direct invoice submission not accepted — must be forwarded by an internal accountant',
    });
    return new Response(JSON.stringify({ ok: false, error: 'direct_invoice_not_accepted' }), {
      status: 400, headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    });
  }

  // ── Deduplication ─────────────────────────────────────────────────────────
  const { data: existingLog } = await supabase
    .from('email_invoice_log')
    .select('id, parse_status, attempt_count')
    .eq('message_id', messageId as string)
    .maybeSingle();

  if (existingLog) {
    const DONE_STATUSES = ['success', 'duplicate'];
    if (DONE_STATUSES.includes(existingLog.parse_status)) {
      return new Response(JSON.stringify({
        ok: true,
        action: 'duplicate',
        message: 'Already processed',
        existingStatus: existingLog.parse_status,
      }), { headers: { ...corsHeaders, 'Content-Type': 'application/json' } });
    }
    await supabase.from('email_invoice_log').delete().eq('id', existingLog.id);
  }

  const attemptCount = existingLog ? (existingLog.attempt_count || 1) + 1 : 1;

  // ── Find user (no auto-creation) ─────────────────────────────────────────
  let userId: string;
  let userName: string;
  let nameUpdated: boolean;

  try {
    const found = await findUser(
      contractorEmail as string,
      contractorName as string | null,
      supabase
    );
    if (!found) {
      await supabase.from('email_invoice_log').insert({
        message_id:      messageId,
        from_email:      contractorEmail,
        subject:         subject || null,
        attachment_name: attachmentName || null,
        parse_status:    'failed',
        parse_notes:     'Unknown contractor — not in profiles. Add user via admin panel first.',
        attempt_count:   attemptCount,
      });
      return new Response(JSON.stringify({ ok: false, error: 'unknown_contractor' }), {
        headers: { ...corsHeaders, 'Content-Type': 'application/json' },
      });
    }
    ({ userId, userName, nameUpdated } = found);
  } catch (e) {
    await supabase.from('email_invoice_log').insert({
      message_id:      messageId,
      from_email:      contractorEmail,
      subject:         subject || null,
      attachment_name: attachmentName || null,
      parse_status:    'failed',
      parse_notes:     `User lookup error: ${String(e)}`,
      attempt_count:   attemptCount,
    });
    return new Response(JSON.stringify({ ok: false, error: String(e) }), {
      status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    });
  }

  // ── Validate we have enough data to create an invoice ────────────────────
  const parsedPeriodStart = periodStart as string | null;
  const parsedPeriodEnd   = periodEnd   as string | null;
  let   parsedHours       = totalHours  != null ? Number(totalHours) : null;
  const parsedAmount      = totalAmount != null ? Number(totalAmount) : null;

  // Allow up to 7 days ahead — some contractors (e.g. Vladimir Šimšić) invoice
  // the full month a few days early. Beyond 7 days is almost certainly a parse error.
  const futureGraceMs = 7 * 24 * 60 * 60 * 1000;
  if (parsedPeriodEnd && new Date(parsedPeriodEnd + 'T12:00:00Z').getTime() > Date.now() + futureGraceMs) {
    const notes = [parseNotes, `Billing period end ${parsedPeriodEnd} is more than 7 days in the future — likely parse error`].filter(Boolean).join(' | ');
    await supabase.from('email_invoice_log').insert({
      message_id: messageId, from_email: contractorEmail, subject,
      attachment_name: attachmentName || null, parse_status: 'partial', parse_notes: notes,
      user_id: userId, attempt_count: attemptCount,
    });
    return new Response(JSON.stringify({ ok: false, action: 'partial', notes }), {
      headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    });
  }

  if (!parsedPeriodStart || !parsedPeriodEnd) {
    const notes = [parseNotes, 'Insufficient data: billing period not found'].filter(Boolean).join(' | ');
    await supabase.from('email_invoice_log').insert({
      message_id:     messageId,
      from_email:     contractorEmail,
      subject,
      attachment_name: attachmentName || null,
      parse_status:   'partial',
      parse_notes:    notes,
      user_id:        userId,
      attempt_count:  attemptCount,
    });
    return new Response(JSON.stringify({ ok: false, action: 'partial', notes }), {
      headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    });
  }

  // Hours are optional. If the invoice parser missed hours, leave parsedHours as null
  // so reconciliation flags the invoice as `unverifiable` for accountant review.
  //
  // Historical note: this block used to fill parsedHours from summed timesheets when
  // the parser missed it. That masked parser failures with wrong-but-plausible numbers.
  // Haris Balavac's June 2026 invoice (id 145) was the canary: PDF clearly said "176   $20   $3,520"
  // but the parser missed 176 and $20 (regex_partial trap). Timesheet-derived fill stored
  // 120h (his in-progress June total at moment of ingest), reconciliation compared
  // 120 vs 160 and flagged `undercharged` — hiding the real gap. Removed 2026-07-01.
  const hoursSourceNote: string | null = null;

  // ── Build invoice record ──────────────────────────────────────────────────
  let invoiceId: number | null = null;
  let parseStatus = 'success';
  let actionNotes = '';
  let reconStatus: 'matched' | 'mismatch' | 'unverifiable' | null = null;
  let reconDelta: number | null = null;
  let resolvedInvoiceNumber: string | null = null;
  // Post-detector period values. Hoisted so the outer log/response can reflect
  // what actually got written. Default to parsed values in case the try block
  // throws before the detector runs.
  let finalPeriodStart = parsedPeriodStart;
  let finalPeriodEnd   = parsedPeriodEnd;
  let detectorFixes: unknown[] = [];
  let detectorFlags: unknown[] = [];

  try {
    const parsedRate     = rate != null ? Number(rate) : null;
    const parsedCurrency = (currency as string) || 'USD';

    // Use parsed invoice number or generate one
    const finalInvoiceNumber = (invoiceNumber as string | null)
      || await generateInvoiceNumber(contractorEmail as string, parsedPeriodStart, supabase);
    resolvedInvoiceNumber = finalInvoiceNumber;

    // Synthetic single line representing the full period.
    // hours/rate may be null for amount-only invoices (no hourly breakdown).
    const initialComputedAmount = parsedAmount
      ?? (parsedHours != null && parsedRate != null ? parsedHours * parsedRate : 0);
    const initialLines = [{
      weekStart:     parsedPeriodStart,
      weekEndingFri: parsedPeriodEnd,
      hours:         parsedHours,
      rate:          parsedRate,
      amount:        initialComputedAmount,
    }];

    // ── Anomaly detection ────────────────────────────────────────────────────
    // Runs before existing-invoice lookup so period corrections affect the
    // duplicate check. Uses prior approved rates + timesheet hours + identity
    // context (company names, currency history, contractor name) as inputs.
    // Fixes rebind final* vars used by both correction and new-insert paths.
    const priorRate      = await getPriorRate(userId, parsedPeriodStart, supabase);
    const preTsSum       = await sumTimesheetHours(userId, parsedPeriodStart, parsedPeriodEnd, supabase);
    const identityCtx    = await getIdentityContext(userId, supabase);
    const parsedCompany  = (paymentDetails as Record<string, string | null> | null)?.companyName || null;
    const detectorResult = detectAnomalies(
      {
        periodStart:       parsedPeriodStart,
        periodEnd:         parsedPeriodEnd,
        hours:             parsedHours,
        rate:              parsedRate,
        amount:            initialComputedAmount,
        currency:          parsedCurrency,
        lines:             initialLines,
        parsedCompanyName: parsedCompany,
      },
      {
        priorRate,
        timesheetHours:        preTsSum ? preTsSum.hours : null,
        expectedCompanies:     identityCtx.companies,
        priorCurrencies:       identityCtx.currencies,
        expectedContractorName: identityCtx.contractorName,
      },
    );

    // Identity mismatch (HIGH) short-circuits payment-profile auto-creation. The parsed
    // company doesn't belong to this contractor — creating a profile under their user_id
    // would leave a phantom pp behind (pre-hotfix Naretena pp id=100 was this bug).
    // Snapshot stays null; accountant assigns during review.
    const hasIdentityMismatch = detectorResult.flags.some(f => f.rule === 'identity_mismatch');

    finalPeriodStart       = detectorResult.corrected.periodStart;
    finalPeriodEnd         = detectorResult.corrected.periodEnd;
    const finalHours       = detectorResult.corrected.hours;
    const finalRate        = detectorResult.corrected.rate;
    const computedAmount   = detectorResult.corrected.amount ?? 0;
    const lines            = detectorResult.corrected.lines;
    detectorFixes          = detectorResult.fixes;
    detectorFlags          = detectorResult.flags;

    // Beneficiary guardrail: skip any convera_beneficiaries flagged deprecated. Events
    // recorded here are appended to invoice.edit_history after insert so accountant sees
    // when the guardrail intervened. Declared at outer scope so both correction-update
    // and new-insert response paths can log them.
    const depMap = await loadDeprecatedBeneMap(supabase);
    const beneGuardrailEvents: Array<{ stage: string; original: number; resolved: number | null; note?: string }> = [];

    // Build payment profile snapshot from parsed bank details (if any).
    // When identity_mismatch fires, we keep the snapshot null — the parsed bank details
    // likely belong to a different contractor, and accountant assigns during review.
    const pd = paymentDetails as Record<string, string | null> | null;

    // IBAN checksum guard (defense in depth — parser.js is authoritative but if a candidate
    // slips through, drop it here so we never store an IBAN that won't route). ISO 13616
    // mod-97. See pp #105 incident: 20-char HR IBAN silently stored, pasted into Convera,
    // then wired successfully to a wrong-length string. Any bad IBAN gets stripped; pp
    // falls back to the SWIFT+account path, and a guardrail event surfaces to the accountant.
    if (pd && pd.iban) {
      const cleanIban = pd.iban.replace(/[^A-Za-z0-9]/g, '').toUpperCase();
      const csValid = (iban: string): boolean => {
        if (!/^[A-Z]{2}\d{2}[A-Z0-9]+$/.test(iban) || iban.length < 15 || iban.length > 34) return false;
        const rearranged = iban.slice(4) + iban.slice(0, 4);
        const numeric = rearranged.replace(/[A-Z]/g, c => (c.charCodeAt(0) - 55).toString());
        let r = 0;
        for (const d of numeric) r = (r * 10 + parseInt(d, 10)) % 97;
        return r === 1;
      };
      if (!csValid(cleanIban)) {
        beneGuardrailEvents.push({
          stage: 'parsed_iban_checksum_failed',
          original: 0, resolved: null,
          note: `Parsed IBAN "${pd.iban}" fails ISO 13616 mod-97 checksum (len ${cleanIban.length}). Stripped from snapshot; accountant to fill from PDF.`,
        });
        pd.iban = '';
      } else if (cleanIban !== pd.iban) {
        pd.iban = cleanIban;
      }
    }

    let paymentProfileSnapshot = (pd && !hasIdentityMismatch) ? {
      id:             0,
      userId,
      profileName:    'Imported',
      companyName:    pd.companyName || '',
      companyAddress: '',
      country:        '',
      bankName:       pd.bankName || '',
      bankAddress:    '',
      bankBranch:     pd.sortCode || '',
      accountNumber:  pd.accountNumber || '',
      iban:           pd.iban || '',
      swift:          pd.swift || '',
      paymentEmail:   '',
      isDefault:      false,
    } : null;

    // ── Resolve payment profile via Convera beneficiary lookup ───────────────
    // Source of truth: convera_beneficiaries (verified bank data from Convera exports).
    // Flow:
    //   1. Incomplete parsed data (no IBAN / no SWIFT+account) → strip; accountant assigns.
    //   2. Already-linked existing payment_profile (same user, matching IBAN/swift+acc) → reuse.
    //      Skipped if the linked bene is deprecated (guardrail).
    //   3. Lookup convera_beneficiaries by IBAN. Deprecated benes filtered out. If 1 match →
    //      hydrate. If multiple (shared intermediary like Bimosoft/NativeTeams/Revolut) →
    //      narrow by short_name containing contractor's name. Create payment_profile linked
    //      to the beneficiary.
    //   4. No beneficiary match → create a "pending" payment_profile from parsed data; it
    //      will be enriched when a future Convera CSV import creates the matching beneficiary.
    if (pd && paymentProfileSnapshot) {
      const norm = (s: string | null | undefined) => (s || '').toUpperCase().replace(/\s+/g, '').trim();
      const unaccent = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '');
      const ibanN  = norm(pd.iban);
      const swiftN = norm(pd.swift);
      const accN   = norm(pd.accountNumber);

      const hasIban   = !!ibanN;
      const hasSwAcc  = !!(swiftN && accN);

      if (!hasIban && !hasSwAcc) {
        // Step 1 — incomplete
        paymentProfileSnapshot = null;
      } else {
        // Step 2 — user's existing profiles
        const { data: existing } = await supabase
          .from('payment_profiles')
          .select('id, profile_name, company_name, company_address, country, bank_name, bank_address, bank_branch, account_number, iban, swift, payment_email, is_default, convera_beneficiary_id')
          .eq('user_id', userId);

        const buildSnapshot = (row: Record<string, unknown>) => ({
          id:             row.id as number,
          userId,
          profileName:    (row.profile_name as string) || 'Imported',
          companyName:    (row.company_name as string) || '',
          companyAddress: (row.company_address as string) || '',
          country:        (row.country as string) || '',
          bankName:       (row.bank_name as string) || '',
          bankAddress:    (row.bank_address as string) || '',
          bankBranch:     (row.bank_branch as string) || '',
          accountNumber:  (row.account_number as string) || '',
          iban:           (row.iban as string) || '',
          swift:          (row.swift as string) || '',
          paymentEmail:   (row.payment_email as string) || '',
          isDefault:      Boolean(row.is_default),
        });

        let resolved = false;

        const existingMatch = hasIban
          ? (existing ?? []).find(p => norm(p.iban) === ibanN)
          : (existing ?? []).find(p => norm(p.swift) === swiftN && norm(p.account_number) === accN);
        if (existingMatch) {
          // Guardrail: if the matched profile is linked to a deprecated bene, look for
          // another profile for the same user linked to the resolved replacement bene
          // (e.g. redirect Amar's IE Revolut profile → his UK ALT profile). If a
          // suitable replacement profile exists, use it. Otherwise fall through so the
          // downstream steps can create/pick a valid one.
          const beneCheck = resolveBene(existingMatch.convera_beneficiary_id as number | null, depMap);
          if (beneCheck.wasDeprecated && beneCheck.resolved != null) {
            const replProfile = (existing ?? []).find(p => p.convera_beneficiary_id === beneCheck.resolved);
            if (replProfile) {
              beneGuardrailEvents.push({
                stage: 'existing_profile_redirected',
                original: beneCheck.original!,
                resolved: beneCheck.resolved,
                note: `Redirected from payment_profile ${existingMatch.id} (deprecated bene ${beneCheck.original}) to payment_profile ${replProfile.id} (bene ${beneCheck.resolved})`,
              });
              paymentProfileSnapshot = buildSnapshot(replProfile);
              resolved = true;
            } else {
              beneGuardrailEvents.push({
                stage: 'existing_profile_deprecated_no_replacement_profile',
                original: beneCheck.original!,
                resolved: beneCheck.resolved,
                note: `Profile ${existingMatch.id} links to deprecated bene ${beneCheck.original}; no user profile links to replacement bene ${beneCheck.resolved}. Falling through — Step 3 will create one.`,
              });
              // fall through — Step 3 will match the parsed IBAN, see deprecation, and
              // create/link a fresh profile pointed at the replacement bene.
            }
          } else if (beneCheck.wasDeprecated) {
            beneGuardrailEvents.push({
              stage: 'existing_profile_deprecated_no_replacement',
              original: beneCheck.original!,
              resolved: null,
              note: `Profile ${existingMatch.id} links to deprecated bene ${beneCheck.original} with no replacement configured. Manual review required.`,
            });
          } else {
            paymentProfileSnapshot = buildSnapshot(existingMatch);
            resolved = true;
          }
        }

        // Phantom-profile guard: if Step 2 did not match, and the parsed IBAN already
        // exists on another user's payment_profile, the sender is almost certainly
        // forwarding on-behalf-of. Auto-creating a new profile under this user_id would
        // leave a phantom (Aug 2026 Naretena pp id=100 bug). Skip Steps 3/3.5/4; leave
        // snapshot null; accountant assigns. Shared-umbrella accounts (Bimosoft/Revolut
        // etc.) are safe: if the sender legitimately shares the umbrella, they already
        // have a profile linked to it and Step 2 matched above.
        let phantomProfileBlocked = false;
        if (!resolved && hasIban) {
          const otherOwners = await findIbanOwnedByOtherUser(ibanN, userId, supabase);
          if (otherOwners.length > 0) {
            phantomProfileBlocked = true;
            paymentProfileSnapshot = null;
            beneGuardrailEvents.push({
              stage: 'phantom_profile_blocked',
              original: 0,
              resolved: null,
              note: `Parsed IBAN ${ibanN} exists on payment_profile(s) [${otherOwners.map(o => o.profileId).join(', ')}] owned by other user(s); sender has no matching profile of their own. Skipped auto-create to prevent phantom profile. Accountant to assign.`,
            });
          }
        }

        // Step 3 — Convera beneficiary lookup. NOTE: convera_beneficiaries.bank_account
        // holds the IBAN (for non-US) or the account number (for US). iban_unique is a
        // BOOLEAN flag (true = unique to this beneficiary, false = shared intermediary like
        // Revolut/Bimosoft). We match the parsed IBAN against bank_account.
        if (!resolved && hasIban && !phantomProfileBlocked) {
          const { data: benefs } = await supabase
            .from('convera_beneficiaries')
            .select('id, short_name, beneficiary_name, beneficiary_country, bank_name, bank_account, iban_unique')
            .ilike('bank_account', ibanN);

          let chosen: Record<string, unknown> | null = null;
          if (benefs && benefs.length === 1) {
            chosen = benefs[0];
          } else if (benefs && benefs.length > 1) {
            // Shared intermediary — disambiguate by user name in short_name
            const userTokens = unaccent((userName as string).toLowerCase())
              .split(/\s+/).filter(t => t.length >= 3);
            chosen = benefs.find(b => {
              const sn = unaccent(((b.short_name as string) || '').toLowerCase());
              return userTokens.some(t => sn.includes(t));
            }) ?? null;
          }

          // Guardrail: if the matched bene is deprecated, resolve to the replacement bene
          // and use that instead (e.g. Bimosoft aux benes → UK ALT). Log the redirection.
          if (chosen) {
            const chosenId = chosen.id as number;
            const beneCheck = resolveBene(chosenId, depMap);
            if (beneCheck.wasDeprecated) {
              if (beneCheck.resolved != null) {
                const { data: replBene } = await supabase
                  .from('convera_beneficiaries')
                  .select('id, short_name, beneficiary_name, beneficiary_country, bank_name, bank_account, iban_unique')
                  .eq('id', beneCheck.resolved)
                  .maybeSingle();
                if (replBene) {
                  beneGuardrailEvents.push({
                    stage: 'iban_match_redirected',
                    original: chosenId,
                    resolved: beneCheck.resolved,
                    note: `IBAN matched deprecated bene ${chosenId} (${(chosen.short_name as string) || ''}); redirected to bene ${beneCheck.resolved} (${(replBene.short_name as string) || ''}).`,
                  });
                  chosen = replBene as Record<string, unknown>;
                } else {
                  beneGuardrailEvents.push({
                    stage: 'iban_match_deprecated_replacement_missing',
                    original: chosenId, resolved: beneCheck.resolved,
                    note: `Replacement bene ${beneCheck.resolved} not found; treating as no match.`,
                  });
                  chosen = null;
                }
              } else {
                beneGuardrailEvents.push({
                  stage: 'iban_match_deprecated_no_replacement',
                  original: chosenId, resolved: null,
                  note: `Matched deprecated bene ${chosenId} with no replacement configured; treating as no match.`,
                });
                chosen = null;
              }
            }
          }

          if (chosen) {
            const alreadyLinked = (existing ?? []).find(p => p.convera_beneficiary_id === chosen!.id);
            if (alreadyLinked) {
              paymentProfileSnapshot = buildSnapshot(alreadyLinked);
              resolved = true;
            } else {
              // bank_account holds IBAN if it starts with 2-letter country code; else account number
              const benefAccount = (chosen.bank_account as string) || '';
              const isIbanFormat = /^[A-Z]{2}\d/.test(benefAccount.replace(/\s+/g, '').toUpperCase());
              // INSERT new payment_profile hydrated from the beneficiary
              const { data: inserted } = await supabase
                .from('payment_profiles')
                .insert({
                  user_id:                userId,
                  profile_name:           (chosen.short_name as string) || 'Imported',
                  company_name:           (chosen.beneficiary_name as string) || pd.companyName || '',
                  country:                (chosen.beneficiary_country as string) || '',
                  bank_name:              (chosen.bank_name as string) || pd.bankName || '',
                  bank_branch:            pd.sortCode || '',
                  account_number:         isIbanFormat ? (pd.accountNumber || '') : (benefAccount || pd.accountNumber || ''),
                  iban:                   isIbanFormat ? benefAccount : (pd.iban || ''),
                  swift:                  pd.swift || '',
                  convera_beneficiary_id: chosen.id,
                  is_default:             false,
                })
                .select('id, profile_name, company_name, company_address, country, bank_name, bank_address, bank_branch, account_number, iban, swift, payment_email, is_default')
                .single();
              if (inserted) {
                paymentProfileSnapshot = buildSnapshot(inserted);
                resolved = true;
              }
            }
          }
        }

        // Step 3.5 — Name-based beneficiary fallback (requires BOTH first and last name
        // as substring in short_name or beneficiary_name). Skips spelling variants by design;
        // accountant handles those manually (one-time link). Phantom guard also applies here.
        if (!resolved && !phantomProfileBlocked) {
          const parts = unaccent((userName as string).toLowerCase()).split(/\s+/).filter(t => t.length >= 3);
          if (parts.length >= 2) {
            const first = parts[0];
            const last = parts[parts.length - 1];
            const { data: nameBenefs } = await supabase
              .from('convera_beneficiaries')
              .select('id, short_name, beneficiary_name, beneficiary_country, bank_name, bank_account, iban_unique')
              .or(`short_name.ilike.*${last}*,beneficiary_name.ilike.*${last}*`);
            const nameMatches = (nameBenefs ?? []).filter(b => {
              const sn = unaccent(((b.short_name as string) || '').toLowerCase());
              const bn = unaccent(((b.beneficiary_name as string) || '').toLowerCase());
              return (sn.includes(first) && sn.includes(last)) || (bn.includes(first) && bn.includes(last));
            });
            if (nameMatches.length === 1) {
              let m = nameMatches[0];
              // Guardrail: if name-matched bene is deprecated, redirect to replacement.
              const beneCheck = resolveBene(m.id as number, depMap);
              if (beneCheck.wasDeprecated) {
                if (beneCheck.resolved != null) {
                  const { data: replBene } = await supabase
                    .from('convera_beneficiaries')
                    .select('id, short_name, beneficiary_name, beneficiary_country, bank_name, bank_account, iban_unique')
                    .eq('id', beneCheck.resolved)
                    .maybeSingle();
                  if (replBene) {
                    beneGuardrailEvents.push({
                      stage: 'name_match_redirected',
                      original: m.id as number,
                      resolved: beneCheck.resolved,
                      note: `Name matched deprecated bene ${m.id}; redirected to bene ${beneCheck.resolved} (${(replBene.short_name as string) || ''}).`,
                    });
                    m = replBene as typeof m;
                  }
                }
                // If replacement missing, fall through — name match "landed" on nothing usable.
                // The subsequent code will still try to link/create; if we can't find a valid
                // target, the invoice ends up in the pending profile path (Step 4).
              }
              const alreadyLinked = (existing ?? []).find(p => p.convera_beneficiary_id === m.id);
              if (alreadyLinked) {
                paymentProfileSnapshot = buildSnapshot(alreadyLinked);
                resolved = true;
              } else {
                const benefAccount = (m.bank_account as string) || '';
                const isIbanFormat = /^[A-Z]{2}\d/.test(benefAccount.replace(/\s+/g, '').toUpperCase());
                const { data: inserted } = await supabase
                  .from('payment_profiles')
                  .insert({
                    user_id:                userId,
                    profile_name:           (m.short_name as string) || 'Imported',
                    company_name:           (m.beneficiary_name as string) || pd.companyName || '',
                    country:                (m.beneficiary_country as string) || '',
                    bank_name:              (m.bank_name as string) || pd.bankName || '',
                    bank_branch:            pd.sortCode || '',
                    account_number:         isIbanFormat ? (pd.accountNumber || '') : (benefAccount || pd.accountNumber || ''),
                    iban:                   isIbanFormat ? benefAccount : (pd.iban || ''),
                    swift:                  pd.swift || '',
                    convera_beneficiary_id: m.id,
                    is_default:             false,
                  })
                  .select('id, profile_name, company_name, company_address, country, bank_name, bank_address, bank_branch, account_number, iban, swift, payment_email, is_default')
                  .single();
                if (inserted) { paymentProfileSnapshot = buildSnapshot(inserted); resolved = true; }
              }
            }
            // If 0 or >1 name matches, fall through to last-used / pending
          }
        }

        // Step 3.6 — Last-used profile fallback. When neither IBAN nor name matched,
        // pull the contractor's most recent prior invoice's payment_profile if it has
        // usable bank data. This is the "they've been paid this way before" signal.
        // Skipped when phantom guard tripped — the "last-used" would carry over the wrong
        // contractor's snapshot if the earlier ingest was itself misrouted.
        if (!resolved && !phantomProfileBlocked) {
          const { data: priorInvoices } = await supabase
            .from('invoices')
            .select('payment_profile')
            .eq('user_id', userId)
            .lt('period_start', finalPeriodStart)
            .not('payment_profile', 'is', null)
            .order('period_start', { ascending: false })
            .limit(5);
          const usefulPrior = (priorInvoices ?? [])
            .map(r => r.payment_profile as Record<string, unknown> | null)
            .find(pp => pp && (pp.iban || pp.accountNumber));
          if (usefulPrior) {
            // Use prior snapshot directly; this is just the JSONB carried over
            paymentProfileSnapshot = { ...paymentProfileSnapshot, ...usefulPrior, userId } as typeof paymentProfileSnapshot;
            resolved = true;
          }
        }

        // Step 4 — no beneficiary match, persist a "pending" profile from parsed data.
        // Phantom guard blocks this too — otherwise we'd create Naretena-pp-100-style ghosts.
        if (!resolved && !phantomProfileBlocked) {
          const monthNames = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
          const [pyear, pmonth] = finalPeriodStart.split('-');
          const periodLabel = `${monthNames[parseInt(pmonth) - 1]} ${pyear}`;
          const { data: inserted } = await supabase
            .from('payment_profiles')
            .insert({
              user_id:         userId,
              profile_name:    `Imported ${periodLabel}`,
              company_name:    pd.companyName || '',
              country:         '',
              bank_name:       pd.bankName || '',
              bank_branch:     pd.sortCode || '',
              account_number:  pd.accountNumber || '',
              iban:            pd.iban || '',
              swift:           pd.swift || '',
              is_default:      false,
            })
            .select('id, profile_name, company_name, company_address, country, bank_name, bank_address, bank_branch, account_number, iban, swift, payment_email, is_default')
            .single();
          if (inserted) paymentProfileSnapshot = buildSnapshot(inserted);
          // If insert failed, fall through with original in-memory snapshot (id=0, name 'Imported')
        }
      }
    }

    // ── Check for existing invoice for same user + period ────────────────────
    // True duplicate → reattach PDF only, no data changes.
    // Correction (fields differ) → update data, reset to submitted, mark corrected.
    const { data: existingInvoice } = await supabase
      .from('invoices')
      .select('id, attachment_path, total_hours, rate, total_amount, status')
      .eq('user_id', userId)
      .eq('period_start', finalPeriodStart)
      .eq('period_end', finalPeriodEnd)
      .eq('source', 'imported')
      .maybeSingle();

    if (existingInvoice) {
      invoiceId = existingInvoice.id;

      const existingHours  = existingInvoice.total_hours  != null ? Number(existingInvoice.total_hours)  : null;
      const existingRate   = existingInvoice.rate          != null ? Number(existingInvoice.rate)          : null;
      const existingAmount = existingInvoice.total_amount  != null ? Number(existingInvoice.total_amount)  : null;
      const isDuplicate    = !correctionHint
                          && existingHours === finalHours
                          && existingRate  === finalRate
                          && Math.abs((existingAmount ?? 0) - computedAmount) < 0.01;

      // Identity-mismatch correction refusal. The classic overwrite bug: an on-behalf-of
      // forwarder's second email (different contractor's PDF, same sender, same month)
      // silently replaced the first ingest's data. Refuse the correction; log as partial.
      // Accountant handles both invoices manually. Aug 2026 Naretena incident: her sender
      // mailbox held Ismir's DEVS IT invoice (parsed at 18:30) and Sivakumar's Procal
      // invoice (parsed at 19:29 → overwrote to $12,880 with stale Ismir pp snapshot).
      if (!isDuplicate && hasIdentityMismatch) {
        const notes = [
          parseNotes,
          `Correction refused: identity_mismatch flag on the incoming parse. ` +
          `Existing invoice id=${invoiceId} preserved. Both PDFs belong to different contractors — accountant to file separately.`,
          ...detectorResult.flags.map(f => `[${f.severity}] ${f.rule}: ${f.message}`),
        ].filter(Boolean).join(' | ');
        await supabase.from('email_invoice_log').insert({
          message_id:      messageId,
          from_email:      contractorEmail,
          subject:         subject || null,
          attachment_name: attachmentName || null,
          parse_status:    'partial',
          parse_notes:     notes,
          user_id:         userId,
          invoice_id:      invoiceId,
          period_start:    finalPeriodStart,
          period_end:      finalPeriodEnd,
          raw_extracted:   body.rawExtracted ?? null,
          attempt_count:   attemptCount,
          attachment_hash: (attachmentHash as string) || null,
          groq_vision_verification: (groqVisionVerification as Record<string, unknown>) || null,
        });
        return new Response(JSON.stringify({
          ok: false,
          action: 'identity_mismatch_correction_refused',
          parseStatus: 'partial',
          userId, userName, invoiceId,
          notes,
          anomalyFlags: detectorResult.flags,
        }), { headers: { ...corsHeaders, 'Content-Type': 'application/json' } });
      }

      if (!isDuplicate) {
        // Correction: update invoice data and reset status for re-approval.
        // invoice_number must be updated too — corrected PDFs often have a new number
        // and the audit trail lives in email_invoice_log.raw_extracted snapshots.
        const updatePayload: Record<string, unknown> = {
          invoice_number: finalInvoiceNumber,
          period_start:   finalPeriodStart,
          period_end:     finalPeriodEnd,
          total_hours:    finalHours,
          rate:           finalRate,
          total_amount:   computedAmount,
          lines,
          corrected:      true,
          status:         'submitted',
          reviewed_at:    null,
          reviewed_by:    null,
        };
        if (paymentProfileSnapshot) updatePayload.payment_profile = paymentProfileSnapshot;

        await supabase.from('invoices').update(updatePayload).eq('id', invoiceId);

        // Upload replacement PDF if provided
        if (pdfBase64 && typeof pdfBase64 === 'string') {
          try {
            const attName2  = (attachmentName as string) || '';
            const extM2     = attName2.match(/\.([a-zA-Z0-9]+)$/);
            const ext2      = extM2 ? extM2[1].toLowerCase() : 'pdf';
            const mimeMap2: Record<string, string> = { pdf: 'application/pdf', docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', doc: 'application/msword' };
            const sp2 = `${invoiceId}/original.${ext2}`;
            const { error: upErr2 } = await supabase.storage
              .from('invoice-attachments')
              .upload(sp2, Uint8Array.from(atob(pdfBase64 as string), c => c.charCodeAt(0)),
                { contentType: mimeMap2[ext2] || 'application/octet-stream', upsert: true });
            if (!upErr2) await supabase.from('invoices').update({ attachment_path: sp2 }).eq('id', invoiceId);
          } catch {}
        }

        actionNotes = `Corrected invoice (id=${invoiceId}): hours ${existingHours}→${finalHours}, rate ${existingRate}→${finalRate}, amount ${existingAmount}→${computedAmount}`;
        await supabase.from('email_invoice_log').insert({
          message_id:      messageId,
          from_email:      contractorEmail,
          subject:         subject || null,
          attachment_name: attachmentName || null,
          parse_status:    'success',
          parse_notes:     [parseNotes, hoursSourceNote, actionNotes].filter(Boolean).join(' | '),
          user_id:         userId,
          invoice_id:      invoiceId,
          period_start:    finalPeriodStart,
          period_end:      finalPeriodEnd,
          raw_extracted:   body.rawExtracted ?? null,
          attempt_count:   attemptCount,
          attachment_hash: (attachmentHash as string) || null,
          groq_vision_verification: (groqVisionVerification as Record<string, unknown>) || null,
        });
        // Append anomaly detector output to edit_history for audit.
        if (detectorResult.fixes.length > 0 || detectorResult.flags.length > 0) {
          await appendAnomalyEditHistory(invoiceId!, detectorResult.fixes, detectorResult.flags, supabase);
        }
        // Append beneficiary guardrail events (skipped deprecated bene links etc).
        if (beneGuardrailEvents.length > 0) {
          await appendGuardrailEditHistory(invoiceId!, beneGuardrailEvents, supabase);
        }
        return new Response(JSON.stringify({
          ok: true, action: 'corrected', parseStatus: 'success',
          userId, userName, invoiceId, invoiceNumber: resolvedInvoiceNumber,
          periodStart: finalPeriodStart, periodEnd: finalPeriodEnd, notes: actionNotes,
          anomalyFixes: detectorResult.fixes, anomalyFlags: detectorResult.flags,
          beneGuardrailEvents,
        }), { headers: { ...corsHeaders, 'Content-Type': 'application/json' } });
      }

      // True duplicate — reattach PDF only
      actionNotes = existingInvoice.attachment_path
        ? `Invoice already exists (id=${invoiceId}) with attachment — skipped`
        : `Invoice already exists (id=${invoiceId}) — attaching PDF only`;

      if (!existingInvoice.attachment_path && pdfBase64 && typeof pdfBase64 === 'string') {
        const attName2 = (attachmentName as string) || '';
        const extM2    = attName2.match(/\.([a-zA-Z0-9]+)$/);
        const ext2     = extM2 ? extM2[1].toLowerCase() : 'pdf';
        const mimeMap2: Record<string, string> = { pdf: 'application/pdf', docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', doc: 'application/msword', msg: 'application/vnd.ms-outlook' };
        const sp2 = `${invoiceId}/original.${ext2}`;
        const { error: upErr } = await supabase.storage
          .from('invoice-attachments')
          .upload(sp2, Uint8Array.from(atob(pdfBase64), c => c.charCodeAt(0)),
            { contentType: mimeMap2[ext2] || 'application/octet-stream', upsert: true });
        if (!upErr) {
          await supabase.from('invoices').update({ attachment_path: sp2 }).eq('id', invoiceId);
          actionNotes = `Re-attached PDF to existing invoice (id=${invoiceId})`;
        } else {
          actionNotes += ` | PDF upload failed: ${upErr.message}`;
        }
      }

      await supabase.from('email_invoice_log').insert({
        message_id:      messageId,
        from_email:      contractorEmail,
        subject:         subject || null,
        attachment_name: attachmentName || null,
        parse_status:    'duplicate',
        parse_notes:     actionNotes,
        user_id:         userId,
        invoice_id:      invoiceId,
        period_start:    finalPeriodStart,
        period_end:      finalPeriodEnd,
        attempt_count:   attemptCount,
        attachment_hash: (attachmentHash as string) || null,
          groq_vision_verification: (groqVisionVerification as Record<string, unknown>) || null,
      });

      return new Response(JSON.stringify({
        ok: true, action: 'reattached', parseStatus: 'duplicate',
        userId, userName, invoiceId, periodStart: finalPeriodStart, notes: actionNotes,
      }), { headers: { ...corsHeaders, 'Content-Type': 'application/json' } });
    }

    // ── Reconcile against approved timesheets (skip for amount-only invoices) ──
    // Uses finalHours/finalPeriodStart/finalPeriodEnd so period corrections from
    // the detector are reflected in the reconciliation status we ship.
    const recon = finalHours != null
      ? await reconcile(userId, finalPeriodStart, finalPeriodEnd, finalHours, supabase)
      : { status: 'unverifiable' as const, delta: null, notes: 'No hours on invoice — amount-only, cannot reconcile' };

    // ── Insert invoice ────────────────────────────────────────────────────
    const { data: inserted, error: insertErr } = await supabase
      .from('invoices')
      .insert({
        user_id:                  userId,
        user_name:                userName,
        project_id:               null,
        invoice_number:           finalInvoiceNumber,
        period_start:             finalPeriodStart,
        period_end:               finalPeriodEnd,
        lines,
        total_hours:              finalHours,
        rate:                     finalRate,
        total_amount:             computedAmount,
        currency:                 parsedCurrency,
        status:                   'submitted',
        submitted_at:             new Date().toISOString(),
        reviewed_at:              null,
        reviewed_by:              null,
        notes:                    '',
        payment_profile:          paymentProfileSnapshot,
        pay_on_date:              null,
        paid_date:                null,
        attachment_path:          null,
        is_vendor_invoice:        false,
        vendor_manager_id:        null,
        source:                   'imported',
        reconciliation_status:    recon.status,
        reconciliation_delta:     recon.delta,
        reconciliation_notes:     recon.notes,
        group_key:                (groupKey as string | null) || null,
      })
      .select('id')
      .single();

    if (insertErr || !inserted) {
      throw new Error(`Invoice insert failed: ${insertErr?.message}`);
    }

    invoiceId = inserted.id;
    reconStatus = recon.status;
    reconDelta  = recon.delta;
    actionNotes = `Reconciliation: ${recon.notes}`;

    // Append anomaly detector output to edit_history for audit.
    if (detectorResult.fixes.length > 0 || detectorResult.flags.length > 0) {
      await appendAnomalyEditHistory(invoiceId, detectorResult.fixes, detectorResult.flags, supabase);
    }
    // Append beneficiary guardrail events (skipped deprecated bene links etc).
    if (beneGuardrailEvents.length > 0) {
      await appendGuardrailEditHistory(invoiceId, beneGuardrailEvents, supabase);
    }

    // ── Upload attachment to storage ──────────────────────────────────────
    if (pdfBase64 && typeof pdfBase64 === 'string') {
      try {
        const attBytes = Uint8Array.from(atob(pdfBase64), c => c.charCodeAt(0));
        const attName = (attachmentName as string) || '';
        const extMatch = attName.match(/\.([a-zA-Z0-9]+)$/);
        const ext = extMatch ? extMatch[1].toLowerCase() : 'pdf';
        const mimeMap: Record<string, string> = {
          pdf:  'application/pdf',
          docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
          doc:  'application/msword',
          msg:  'application/vnd.ms-outlook',
        };
        const contentType = mimeMap[ext] || 'application/octet-stream';
        const storagePath = `${invoiceId}/original.${ext}`;

        const { error: uploadErr } = await supabase.storage
          .from('invoice-attachments')
          .upload(storagePath, attBytes, { contentType, upsert: false });

        if (uploadErr) {
          console.warn(`Attachment upload failed for invoice ${invoiceId}: ${uploadErr.message}`);
        } else {
          await supabase
            .from('invoices')
            .update({ attachment_path: storagePath })
            .eq('id', invoiceId);
        }
      } catch (uploadEx) {
        console.warn(`Attachment upload exception for invoice ${invoiceId}: ${String(uploadEx)}`);
      }
    }

  } catch (e) {
    parseStatus = 'failed';
    actionNotes = `Invoice error: ${String(e)}`;
  }

  // ── Log ───────────────────────────────────────────────────────────────────
  await supabase.from('email_invoice_log').insert({
    message_id:      messageId,
    from_email:      contractorEmail,
    subject:         subject || null,
    attachment_name: attachmentName || null,
    parse_status:    parseStatus,
    parse_notes:     [parseNotes, hoursSourceNote, actionNotes].filter(Boolean).join(' | '),
    user_id:         userId,
    invoice_id:      invoiceId,
    period_start:    finalPeriodStart,
    period_end:      finalPeriodEnd,
    raw_extracted:   body.rawExtracted ?? null,
    attempt_count:   attemptCount,
    attachment_hash: (attachmentHash as string) || null,
          groq_vision_verification: (groqVisionVerification as Record<string, unknown>) || null,
  });

  return new Response(JSON.stringify({
    ok:                  parseStatus === 'success',
    action:              invoiceId ? 'created' : 'failed',
    parseStatus,
    userId,
    userName,
    nameUpdated,
    invoiceId,
    invoiceNumber:       resolvedInvoiceNumber,
    periodStart:         finalPeriodStart,
    periodEnd:           finalPeriodEnd,
    forwardedBy:         forwardedBy || null,
    reconciliationStatus: reconStatus,
    reconciliationDelta:  reconDelta,
    notes:               actionNotes,
    anomalyFixes:        detectorFixes,
    anomalyFlags:        detectorFlags,
    beneGuardrailEvents,
    attemptCount,
  }), { headers: { ...corsHeaders, 'Content-Type': 'application/json' } });
});
